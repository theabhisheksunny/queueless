package com.queueless.security;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.security.*;
import java.security.spec.*;
import java.util.Base64;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

@Component
public class DeviceCryptoUtil {

    private static final Logger log = LoggerFactory.getLogger(DeviceCryptoUtil.class);
    private static final Pattern JWK_X_PATTERN = Pattern.compile("\"x\"\\s*:\\s*\"([^\"]+)\"");
    private static final Pattern JWK_Y_PATTERN = Pattern.compile("\"y\"\\s*:\\s*\"([^\"]+)\"");

    /**
     * Verifies an ECDSA P-256 signature over the given data payload.
     * Supports both raw IEEE P1363 signatures (64 bytes generated by Web Crypto API)
     * and standard ASN.1 DER-encoded signatures.
     */
    public boolean verifySignature(String publicKeyStr, String payload, String signatureBase64) {
        if (publicKeyStr == null || publicKeyStr.isBlank() || payload == null || signatureBase64 == null) {
            return false;
        }

        try {
            PublicKey publicKey = parsePublicKey(publicKeyStr);
            byte[] sigBytes = Base64.getDecoder().decode(signatureBase64.trim());
            byte[] dataBytes = payload.getBytes(StandardCharsets.UTF_8);

            // Attempt verification with P1363 (standard 64-byte Web Crypto output)
            if (sigBytes.length == 64) {
                try {
                    Signature sigP1363 = Signature.getInstance("SHA256withECDSAinP1363Format");
                    sigP1363.initVerify(publicKey);
                    sigP1363.update(dataBytes);
                    if (sigP1363.verify(sigBytes)) {
                        return true;
                    }
                } catch (NoSuchAlgorithmException ignored) {
                    // Fall back to DER conversion if P1363 algorithm not available
                }
                // Try converting P1363 to DER
                byte[] derSig = p1363ToDer(sigBytes);
                if (derSig != null) {
                    Signature sigDer = Signature.getInstance("SHA256withECDSA");
                    sigDer.initVerify(publicKey);
                    sigDer.update(dataBytes);
                    if (sigDer.verify(derSig)) {
                        return true;
                    }
                }
            }

            // Standard DER signature
            Signature sig = Signature.getInstance("SHA256withECDSA");
            sig.initVerify(publicKey);
            sig.update(dataBytes);
            return sig.verify(sigBytes);

        } catch (Exception e) {
            log.warn("Device cryptographic signature verification failed: {}", e.getMessage());
            return false;
        }
    }

    /**
     * Parses a public key string from either X.509 SPKI Base64 or JWK JSON format.
     */
    public PublicKey parsePublicKey(String publicKeyStr) throws GeneralSecurityException {
        String clean = publicKeyStr.trim();
        KeyFactory kf = KeyFactory.getInstance("EC");

        // Case 1: JWK JSON format {"kty":"EC","crv":"P-256","x":"...","y":"..."}
        if (clean.startsWith("{") && clean.contains("\"x\"") && clean.contains("\"y\"")) {
            Matcher mX = JWK_X_PATTERN.matcher(clean);
            Matcher mY = JWK_Y_PATTERN.matcher(clean);
            if (mX.find() && mY.find()) {
                byte[] xBytes = Base64.getUrlDecoder().decode(mX.group(1));
                byte[] yBytes = Base64.getUrlDecoder().decode(mY.group(1));
                BigInteger x = new BigInteger(1, xBytes);
                BigInteger y = new BigInteger(1, yBytes);
                ECPoint point = new ECPoint(x, y);

                AlgorithmParameters params = AlgorithmParameters.getInstance("EC");
                params.init(new ECGenParameterSpec("secp256r1"));
                ECParameterSpec ecParams = params.getParameterSpec(ECParameterSpec.class);

                return kf.generatePublic(new ECPublicKeySpec(point, ecParams));
            }
        }

        // Case 2: X.509 SPKI Base64 format
        String pem = clean
                .replace("-----BEGIN PUBLIC KEY-----", "")
                .replace("-----END PUBLIC KEY-----", "")
                .replaceAll("\\s+", "");
        byte[] spkiBytes = Base64.getDecoder().decode(pem);
        return kf.generatePublic(new X509EncodedKeySpec(spkiBytes));
    }

    /**
     * Converts a 64-byte IEEE P1363 (r || s) signature to ASN.1 DER format.
     */
    private byte[] p1363ToDer(byte[] p1363) {
        if (p1363.length != 64) return null;
        try {
            byte[] r = new byte[32];
            byte[] s = new byte[32];
            System.arraycopy(p1363, 0, r, 0, 32);
            System.arraycopy(p1363, 32, s, 0, 32);

            BigInteger rInt = new BigInteger(1, r);
            BigInteger sInt = new BigInteger(1, s);

            byte[] rBytes = rInt.toByteArray();
            byte[] sBytes = sInt.toByteArray();

            int len = 2 + rBytes.length + 2 + sBytes.length;
            byte[] der = new byte[2 + len];
            der[0] = 0x30; // SEQUENCE
            der[1] = (byte) len;
            der[2] = 0x02; // INTEGER
            der[3] = (byte) rBytes.length;
            System.arraycopy(rBytes, 0, der, 4, rBytes.length);

            int sOffset = 4 + rBytes.length;
            der[sOffset] = 0x02; // INTEGER
            der[sOffset + 1] = (byte) sBytes.length;
            System.arraycopy(sBytes, 0, der, sOffset + 2, sBytes.length);

            return der;
        } catch (Exception e) {
            return null;
        }
    }
}
