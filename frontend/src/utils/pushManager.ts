import { api } from '../api/client';

export function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/');
  const rawData = window.atob(base64);
  const outputArray = new Uint8Array(rawData.length);
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

export function isPushSupported(): boolean {
  return (
    typeof window !== 'undefined' &&
    'serviceWorker' in navigator &&
    'Notification' in window
  );
}

export function isIosDevice(): boolean {
  if (typeof window === 'undefined' || typeof navigator === 'undefined') return false;
  return /iPad|iPhone|iPod/.test(navigator.userAgent) || (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);
}

export function isIosStandalone(): boolean {
  if (typeof window === 'undefined') return false;
  return (
    window.matchMedia('(display-mode: standalone)').matches ||
    Boolean((window.navigator as any).standalone)
  );
}

export type PushStatus =
  | 'unsupported'
  | 'ios_needs_pwa'
  | 'denied'
  | 'subscribed'
  | 'unsubscribed'
  | 'loading';

export async function checkPushStatus(_trackingToken?: string): Promise<PushStatus> {
  if (!isPushSupported()) {
    if (isIosDevice() && !isIosStandalone()) {
      return 'ios_needs_pwa';
    }
    return 'unsupported';
  }

  if (typeof Notification !== 'undefined' && Notification.permission === 'denied') {
    return 'denied';
  }

  try {
    if ('serviceWorker' in navigator) {
      const registration = await navigator.serviceWorker.getRegistration();
      if (registration && registration.pushManager) {
        const subscription = await registration.pushManager.getSubscription();
        if (subscription) {
          return 'subscribed';
        }
      }
    }
  } catch (err) {
    console.error('Error checking push subscription:', err);
  }

  return 'unsubscribed';
}

export async function subscribeCustomerPush(trackingToken: string): Promise<{ success: boolean; error?: string }> {
  if (!isPushSupported()) {
    if (isIosDevice() && !isIosStandalone()) {
      return { success: false, error: 'ios_needs_pwa' };
    }
    return { success: false, error: 'Web Push is not supported in this browser.' };
  }

  try {
    // 1. Request notification permission
    const permission = await Notification.requestPermission();
    if (permission !== 'granted') {
      return { success: false, error: 'Notification permission was ' + permission };
    }

    // 2. Register Service Worker
    const registration = await navigator.serviceWorker.register('/sw.js');

    // 3. Fetch VAPID public key from backend
    const { publicKey } = await api.getVapidPublicKey();
    if (!publicKey) {
      throw new Error('VAPID public key not found from server');
    }

    const applicationServerKey = urlBase64ToUint8Array(publicKey);

    // 4. Subscribe with PushManager
    let subscription = await registration.pushManager.getSubscription();
    if (!subscription) {
      subscription = await registration.pushManager.subscribe({
        userVisibleOnly: true,
        applicationServerKey: applicationServerKey as any,
      });
    }

    const subJson = subscription.toJSON();
    if (!subJson.endpoint || !subJson.keys?.p256dh || !subJson.keys?.auth) {
      throw new Error('Invalid subscription keys generated by browser');
    }

    // 5. Send subscription to backend linked with customer trackingToken
    await api.registerPushSubscription(trackingToken, {
      endpoint: subJson.endpoint,
      p256dh: subJson.keys.p256dh,
      auth: subJson.keys.auth,
      userAgent: navigator.userAgent,
    });

    return { success: true };
  } catch (err: any) {
    console.error('Failed to subscribe to Web Push:', err);
    return { success: false, error: err.message || 'Subscription failed' };
  }
}

export async function unsubscribeCustomerPush(trackingToken: string): Promise<boolean> {
  try {
    if ('serviceWorker' in navigator) {
      const registration = await navigator.serviceWorker.getRegistration();
      if (registration) {
        const subscription = await registration.pushManager.getSubscription();
        if (subscription) {
          await subscription.unsubscribe();
        }
      }
    }
    await api.unregisterPushSubscription(trackingToken);
    return true;
  } catch (err) {
    console.error('Failed to unsubscribe from push:', err);
    return false;
  }
}

export async function clearActiveQueueNotifications(trackingToken?: string): Promise<void> {
  try {
    if (typeof window !== 'undefined' && 'serviceWorker' in navigator) {
      const registration = await navigator.serviceWorker.getRegistration();
      if (registration) {
        const tag = trackingToken ? `queueless-queue-${trackingToken}` : undefined;
        const notifications = await registration.getNotifications(tag ? { tag } : undefined);
        for (const n of notifications) {
          n.close();
        }
      }
    }
  } catch (err) {
    console.error('Failed to clear notifications:', err);
  }
}
